import { ja, type MessageKey } from "../locales/ja.js";

export type { MessageKey };

/**
 * 文言を引く。
 *
 * 戻り値は `string`。`ja` の値の型（リテラル）をそのまま返すと、
 * 呼び出し側で文言の中身に依存した型が生まれる。**文言は差し替わるもの**なので
 * ここで幅を広げておく。
 */
export function t(key: MessageKey): string {
  return ja[key];
}
