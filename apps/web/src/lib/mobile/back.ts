/**
 * 現場画面（`/m/*`）の戻り先（人間の指示 2026-08-22 / DECISIONS #259）。
 *
 * ── 履歴に頼らない ──────────────────────────────────────
 * `navigate(-1)` は**押した人がどう来たか**で行き先が変わる。現場の端末で
 * それが崩れる場面は珍しくない。
 *
 * | 場面 | `history.go(-1)` の結果 |
 * |---|---|
 * | ホーム画面の PWA を起動して開いた | **戻る先が無い**（押しても動かない） |
 * | URL を直接開いた・再読み込みした | 同上 |
 * | 別の画面を経由して来た | **業務上の親ではない画面**へ戻る |
 *
 * だから戻り先は**いま開いている資源から決める。** ここはその 1 行を持つ
 * 純粋関数で、**画面もフレームワークも見ない**（`back.spec.ts` が固定する）。
 */

/** 現場のホーム（タスク一覧）。 */
export const MOBILE_HOME = "/m/today";

/**
 * タスクに属する画面から戻る先。
 *
 * タスクが分かればその詳細へ、分からなければ一覧へ。**どちらの場合も
 * 具体的な URL が決まる**（空文字や `undefined` を返さない）。
 */
export function taskBackPath(taskId: string | null): string {
  return taskId === null ? MOBILE_HOME : `/m/task/${taskId}`;
}
